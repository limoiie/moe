//! Model catalog: the embedded models.dev snapshot, the runtime cache, and the
//! daily ETag-conditional refresh (MOE-0025, `docs/research/ai-model-catalogs.md`).
//!
//! Read precedence: the cached copy (`data_dir/moe/models-catalog.json`) overlays the
//! embedded baseline (`data/`, reduced fields, official providers); a provider present
//! in both takes the cached version. [`refresh_if_stale`] performs at most one
//! conditional `GET` per [`STALE_AFTER_SECS`]; failures leave the previous state
//! untouched, so callers can run it on a background thread and ignore errors.
//!
//! The embedded snapshot is generated by `scripts/refresh-models-catalog.sh` — never
//! edit it by hand (see `crates/moe-platform/data/README.md`).

use std::collections::BTreeMap;
use std::fmt;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;
use std::time::Duration;

use serde::{Deserialize, Serialize};

/// The upstream catalog (MIT, Copyright (c) 2025 models.dev).
pub const CATALOG_URL: &str = "https://models.dev/api.json";

/// A cached copy older than this triggers a refresh attempt.
pub const STALE_AFTER_SECS: u64 = 24 * 60 * 60;

const USER_AGENT: &str = "moe/0.1 (model catalog refresh)";
const REQUEST_TIMEOUT: Duration = Duration::from_secs(30);

const EMBEDDED_CATALOG_JSON: &str = include_str!("../data/models-catalog.json");

/// `data_dir/moe/models-catalog.json` — the runtime cache (macOS: ~/Library/Application
/// Support; Linux: ~/.local/share); the embedded baseline lives in `data/` at compile time.
pub fn catalog_path() -> Option<PathBuf> {
    dirs::data_dir().map(|dir| dir.join("moe").join("models-catalog.json"))
}

/// The embedded baseline, parsed once. Panics only if the committed snapshot is invalid
/// JSON, which the refresh workflow and CI exist to prevent.
pub fn embedded() -> &'static Catalog {
    static EMBEDDED: OnceLock<Catalog> = OnceLock::new();
    EMBEDDED.get_or_init(|| {
        serde_json::from_str(EMBEDDED_CATALOG_JSON).expect("embedded model catalog parses")
    })
}

/// The catalog for the default data dir: the cache overlays the embedded baseline.
pub fn load() -> Catalog {
    match catalog_path() {
        Some(path) => load_at(&path),
        None => embedded().clone(),
    }
}

/// [`load`] against an explicit cache path (tests, embedders).
pub fn load_at(path: &Path) -> Catalog {
    match read_cache(path) {
        Some(cache) => overlay(embedded().clone(), cache.catalog),
        None => embedded().clone(),
    }
}

/// Refresh the default data dir's cache when it is missing or older than
/// [`STALE_AFTER_SECS`]. Returns [`RefreshOutcome::Skipped`] when there is no data dir.
pub fn refresh_if_stale(now_unix: u64) -> Result<RefreshOutcome, CatalogError> {
    let Some(path) = catalog_path() else {
        return Ok(RefreshOutcome::Skipped);
    };
    refresh_at(&path, CATALOG_URL, now_unix)
}

/// [`refresh_if_stale`] against an explicit cache path and endpoint (tests).
///
/// On `304 Not Modified` the cache's timestamp is bumped without rewriting the catalog;
/// on `200` the fetched body replaces the cache (atomically); any error — network,
/// status, parse — returns before touching the file, keeping the previous state.
pub fn refresh_at(path: &Path, url: &str, now_unix: u64) -> Result<RefreshOutcome, CatalogError> {
    let cached = read_cache(path);
    if let Some(cache) = &cached
        && !is_stale(cache.fetched_at_unix, now_unix)
    {
        return Ok(RefreshOutcome::Fresh);
    }

    let client = reqwest::blocking::Client::builder()
        .timeout(REQUEST_TIMEOUT)
        .user_agent(USER_AGENT)
        .build()
        .map_err(|err| CatalogError::Http(err.to_string()))?;
    let mut request = client.get(url);
    if let Some(etag) = cached.as_ref().and_then(|cache| cache.etag.clone()) {
        request = request.header(reqwest::header::IF_NONE_MATCH, etag);
    }
    let response = request
        .send()
        .map_err(|err| CatalogError::Http(err.to_string()))?;

    let status = response.status();
    if status == reqwest::StatusCode::NOT_MODIFIED {
        if let Some(mut cache) = cached {
            cache.fetched_at_unix = now_unix;
            write_cache(path, &cache)?;
        }
        return Ok(RefreshOutcome::NotModified);
    }
    if !status.is_success() {
        return Err(CatalogError::Http(format!("unexpected status {status}")));
    }

    let etag = response
        .headers()
        .get(reqwest::header::ETAG)
        .and_then(|value| value.to_str().ok())
        .map(str::to_string);
    let body = response
        .text()
        .map_err(|err| CatalogError::Http(err.to_string()))?;
    let catalog: Catalog =
        serde_json::from_str(&body).map_err(|err| CatalogError::Parse(err.to_string()))?;
    write_cache(
        path,
        &CatalogCache {
            etag,
            fetched_at_unix: now_unix,
            catalog,
        },
    )?;
    Ok(RefreshOutcome::Updated)
}

/// Whether a cache stamped `fetched_at_unix` needs a refresh at `now_unix`
/// (24 h window; a backwards clock stays fresh).
pub fn is_stale(fetched_at_unix: u64, now_unix: u64) -> bool {
    now_unix.saturating_sub(fetched_at_unix) >= STALE_AFTER_SECS
}

/// Merge: `cached` wins on provider-id collisions; providers only in `base` survive.
pub fn overlay(base: Catalog, cached: Catalog) -> Catalog {
    let mut merged = base;
    for (id, provider) in cached.0 {
        merged.0.insert(id, provider);
    }
    merged
}

fn read_cache(path: &Path) -> Option<CatalogCache> {
    let text = std::fs::read_to_string(path).ok()?;
    match serde_json::from_str(&text) {
        Ok(cache) => Some(cache),
        Err(err) => {
            eprintln!(
                "moe: ignoring unreadable model catalog cache {} ({err})",
                path.display()
            );
            None
        }
    }
}

fn write_cache(path: &Path, cache: &CatalogCache) -> Result<(), CatalogError> {
    if let Some(dir) = path.parent()
        && let Err(err) = std::fs::create_dir_all(dir)
    {
        return Err(CatalogError::Io(err));
    }
    let json = serde_json::to_string(cache).map_err(|err| CatalogError::Parse(err.to_string()))?;
    // Atomic replace: a failed refresh never leaves a half-written cache behind.
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);
    std::fs::write(&tmp, json)?;
    std::fs::rename(&tmp, path)?;
    Ok(())
}

/// The result of one [`refresh_if_stale`] call.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RefreshOutcome {
    /// No data dir to cache into.
    Skipped,
    /// The cache is younger than [`STALE_AFTER_SECS`]; no request was made.
    Fresh,
    /// The upstream answered `304`; only the timestamp moved.
    NotModified,
    /// A new snapshot was fetched and cached.
    Updated,
}

#[derive(Debug)]
pub enum CatalogError {
    /// The request failed or answered an unexpected status.
    Http(String),
    /// The fetched body is not catalog JSON.
    Parse(String),
    /// The cache file could not be read or written.
    Io(std::io::Error),
}

impl fmt::Display for CatalogError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Http(message) => write!(f, "model catalog HTTP error: {message}"),
            Self::Parse(message) => write!(f, "model catalog parse error: {message}"),
            Self::Io(err) => write!(f, "model catalog cache I/O error: {err}"),
        }
    }
}

impl std::error::Error for CatalogError {}

impl From<std::io::Error> for CatalogError {
    fn from(err: std::io::Error) -> Self {
        Self::Io(err)
    }
}

/// One provider entry from models.dev — enough to prefill an "add provider" form
/// (`api`, `env`, `doc`) and to list its models.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Provider {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub name: String,
    /// API-key environment variable names (keychain onboarding hint).
    #[serde(default)]
    pub env: Vec<String>,
    /// OpenAI-compatible base URL (SDK-native providers leave it empty).
    #[serde(default)]
    pub api: Option<String>,
    /// Documentation link.
    #[serde(default)]
    pub doc: Option<String>,
    /// The AI SDK package upstream uses; a protocol hint (see MOE-0025 research notes).
    #[serde(default)]
    pub npm: Option<String>,
    #[serde(default)]
    pub models: BTreeMap<String, Model>,
}

/// One model entry: limits, capabilities, modalities, pricing, dates.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Model {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub name: String,
    /// Accepts file attachments.
    #[serde(default)]
    pub attachment: bool,
    #[serde(default)]
    pub reasoning: bool,
    #[serde(default)]
    pub reasoning_options: Vec<ReasoningOption>,
    /// The field a provider echoes reasoning into (e.g. `reasoning_content`).
    #[serde(default)]
    pub interleaved: Option<Interleaved>,
    #[serde(default)]
    pub tool_call: bool,
    #[serde(default)]
    pub structured_output: bool,
    /// Knowledge cutoff (`YYYY-MM` or `YYYY-MM-DD`).
    #[serde(default)]
    pub knowledge: Option<String>,
    #[serde(default)]
    pub release_date: Option<String>,
    #[serde(default)]
    pub last_updated: Option<String>,
    #[serde(default)]
    pub modalities: Modalities,
    #[serde(default)]
    pub open_weights: bool,
    #[serde(default)]
    pub limit: Option<Limit>,
    /// USD per million tokens.
    #[serde(default)]
    pub cost: Option<Cost>,
    /// `alpha` / `beta` / `deprecated` when set.
    #[serde(default)]
    pub status: Option<String>,
    /// Links a provider model to its lab-canonical model in models.dev.
    #[serde(default)]
    pub canonical_model_id: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ReasoningOption {
    #[serde(rename = "type", default)]
    pub kind: String,
    #[serde(default)]
    pub values: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Interleaved {
    #[serde(default)]
    pub field: Option<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Modalities {
    #[serde(default)]
    pub input: Vec<String>,
    #[serde(default)]
    pub output: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Limit {
    #[serde(default)]
    pub context: Option<u64>,
    #[serde(default)]
    pub output: Option<u64>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Cost {
    #[serde(default)]
    pub input: Option<f64>,
    #[serde(default)]
    pub output: Option<f64>,
    #[serde(default)]
    pub reasoning: Option<f64>,
    #[serde(default)]
    pub cache_read: Option<f64>,
    #[serde(default)]
    pub cache_write: Option<f64>,
    #[serde(default)]
    pub input_audio: Option<f64>,
    #[serde(default)]
    pub output_audio: Option<f64>,
}

/// Provider map keyed by models.dev provider id.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Catalog(BTreeMap<String, Provider>);

impl Catalog {
    pub fn get(&self, provider_id: &str) -> Option<&Provider> {
        self.0.get(provider_id)
    }

    pub fn providers(&self) -> impl Iterator<Item = &Provider> {
        self.0.values()
    }

    /// Provider id + entry pairs: the id is the map key, which is authoritative (the embedded
    /// entry's own `id` field may be absent — a hand-built or overlaid entry need not carry it).
    pub fn entries(&self) -> impl Iterator<Item = (&str, &Provider)> {
        self.0.iter().map(|(id, provider)| (id.as_str(), provider))
    }

    pub fn len(&self) -> usize {
        self.0.len()
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }
}

/// The cache file's envelope: the snapshot plus what the next refresh needs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
struct CatalogCache {
    #[serde(default)]
    etag: Option<String>,
    fetched_at_unix: u64,
    catalog: Catalog,
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::{Read, Write};
    use std::net::TcpListener;
    use std::sync::{Arc, Mutex};

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "moe-model-catalog-test-{}-{tag}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// Serve `responses` (raw HTTP bytes) over one connection each; capture the request heads.
    fn serve(
        responses: Vec<String>,
    ) -> (String, Arc<Mutex<Vec<String>>>, std::thread::JoinHandle<()>) {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let addr = listener.local_addr().unwrap();
        let requests = Arc::new(Mutex::new(Vec::new()));
        let captured = requests.clone();
        let handle = std::thread::spawn(move || {
            for response in responses {
                let (mut stream, _) = listener.accept().unwrap();
                let mut buf = [0u8; 4096];
                let read = stream.read(&mut buf).unwrap_or(0);
                captured
                    .lock()
                    .unwrap()
                    .push(String::from_utf8_lossy(&buf[..read]).into_owned());
                let _ = stream.write_all(response.as_bytes());
                let _ = stream.flush();
            }
        });
        (format!("http://{addr}/api.json"), requests, handle)
    }

    fn http_response(status: &str, extra_headers: &str, body: &str) -> String {
        format!(
            "HTTP/1.1 {status}\r\n{extra_headers}Content-Length: {}\r\nConnection: close\r\n\r\n{body}",
            body.len()
        )
    }

    fn catalog_of(providers: Vec<Provider>) -> Catalog {
        Catalog(providers.into_iter().map(|p| (p.id.clone(), p)).collect())
    }

    #[test]
    fn embedded_snapshot_parses_and_round_trips() {
        let catalog = embedded();
        assert!(
            catalog.len() >= 10,
            "expected the official providers, got {}",
            catalog.len()
        );
        for provider in catalog.providers() {
            assert!(!provider.id.is_empty());
            assert!(!provider.name.is_empty());
            assert!(!provider.models.is_empty(), "{} has no models", provider.id);
        }
        // Stable anchors: official providers the script always keeps.
        assert!(catalog.get("openai").is_some());
        assert!(catalog.get("anthropic").is_some());
        assert!(catalog.get("deepseek").is_some());
        // The picker fields survive: some model carries limits and a context window.
        assert!(
            catalog
                .providers()
                .flat_map(|p| p.models.values())
                .any(|m| m.limit.as_ref().and_then(|l| l.context).is_some())
        );
        // Serialize → parse is lossless (the cache uses the same shape).
        let json = serde_json::to_string(catalog).unwrap();
        let back: Catalog = serde_json::from_str(&json).unwrap();
        assert_eq!(&back, catalog);
    }

    #[test]
    fn staleness_uses_a_24_hour_window() {
        assert!(!is_stale(1_000, 1_000));
        assert!(!is_stale(1_000, 1_000 + STALE_AFTER_SECS - 1));
        assert!(is_stale(1_000, 1_000 + STALE_AFTER_SECS));
        // A backwards clock never refreshes in a loop.
        assert!(!is_stale(1_000, 500));
    }

    #[test]
    fn overlay_prefers_the_cached_catalog() {
        let base = catalog_of(vec![
            Provider {
                id: "a".into(),
                name: "Base A".into(),
                ..Provider::default()
            },
            Provider {
                id: "b".into(),
                name: "Base B".into(),
                ..Provider::default()
            },
        ]);
        let cached = catalog_of(vec![Provider {
            id: "a".into(),
            name: "Cached A".into(),
            ..Provider::default()
        }]);
        let merged = overlay(base, cached);
        assert_eq!(merged.get("a").unwrap().name, "Cached A");
        assert_eq!(merged.get("b").unwrap().name, "Base B");
    }

    #[test]
    fn load_overlays_the_cache_and_falls_back_to_embedded() {
        let dir = temp_dir("load");
        let path = dir.join("models-catalog.json");

        // No cache: the embedded baseline.
        let embedded_only = load_at(&path);
        assert!(embedded_only.get("openai").is_some());

        // A crafted cache wins for its providers and adds new ones; embedded providers survive.
        let cache = CatalogCache {
            etag: None,
            fetched_at_unix: 0,
            catalog: catalog_of(vec![
                Provider {
                    id: "deepseek".into(),
                    name: "CACHED".into(),
                    ..Provider::default()
                },
                Provider {
                    id: "acme".into(),
                    name: "Acme".into(),
                    ..Provider::default()
                },
            ]),
        };
        std::fs::write(&path, serde_json::to_string(&cache).unwrap()).unwrap();
        let loaded = load_at(&path);
        assert_eq!(loaded.get("deepseek").unwrap().name, "CACHED");
        assert!(loaded.get("acme").is_some());
        assert!(
            loaded.get("openai").is_some(),
            "embedded-only providers survive the overlay"
        );

        // Corrupt cache: silently back to embedded.
        std::fs::write(&path, "not json at all").unwrap();
        let fallback = load_at(&path);
        assert_ne!(fallback.get("deepseek").unwrap().name, "CACHED");
        assert!(fallback.get("openai").is_some());

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn refresh_writes_the_cache_then_revalidates_with_304() {
        let dir = temp_dir("refresh");
        let path = dir.join("models-catalog.json");

        let body = r#"{"acme":{"id":"acme","name":"Acme","env":["ACME_API_KEY"],"api":"https://api.acme.test/v1","models":{"m1":{"id":"m1","name":"M1","limit":{"context":128000,"output":8192}}}}}"#;
        let ok = http_response(
            "200 OK",
            "Content-Type: application/json\r\nETag: W/\"test-etag\"\r\n",
            body,
        );
        let not_modified =
            "HTTP/1.1 304 Not Modified\r\nETag: W/\"test-etag\"\r\nConnection: close\r\n\r\n"
                .to_string();
        let (url, requests, server) = serve(vec![ok, not_modified]);

        // First call: stale by definition (no cache) → fetch and cache.
        let first = refresh_at(&path, &url, 1_000).unwrap();
        assert_eq!(first, RefreshOutcome::Updated);
        let cached: CatalogCache =
            serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
        assert_eq!(cached.fetched_at_unix, 1_000);
        assert_eq!(cached.etag.as_deref(), Some("W/\"test-etag\""));
        assert_eq!(
            cached.catalog.get("acme").unwrap().models["m1"]
                .limit
                .as_ref()
                .unwrap()
                .context,
            Some(128_000)
        );

        // Fresh cache → no request at all (the server only answers two connections).
        let fresh = refresh_at(&path, &url, 1_000 + STALE_AFTER_SECS - 1).unwrap();
        assert_eq!(fresh, RefreshOutcome::Fresh);

        // Stale cache → conditional GET; the server answers 304; only the stamp moves.
        let revalidated = refresh_at(&path, &url, 1_000 + STALE_AFTER_SECS + 1).unwrap();
        assert_eq!(revalidated, RefreshOutcome::NotModified);
        let after: CatalogCache =
            serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
        assert_eq!(after.fetched_at_unix, 1_000 + STALE_AFTER_SECS + 1);
        assert_eq!(
            after.catalog, cached.catalog,
            "304 keeps the cached catalog"
        );

        server.join().unwrap();
        let requests = requests.lock().unwrap();
        assert_eq!(requests.len(), 2, "fresh cache must not hit the network");
        assert!(requests[0].starts_with("GET /api.json"));
        assert!(
            requests[1]
                .to_ascii_lowercase()
                .contains("if-none-match: w/\"test-etag\""),
            "the revalidation must be conditional: {}",
            requests[1]
        );

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn refresh_keeps_the_old_cache_on_error() {
        let dir = temp_dir("refresh-errors");
        let path = dir.join("models-catalog.json");
        let body = r#"{"acme":{"id":"acme","name":"Acme","models":{"m1":{"id":"m1"}}}}"#;
        let (url_ok, _, server_ok) = serve(vec![http_response("200 OK", "ETag: \"e1\"\r\n", body)]);
        assert_eq!(
            refresh_at(&path, &url_ok, 1_000).unwrap(),
            RefreshOutcome::Updated
        );
        server_ok.join().unwrap();

        // 500: the previous cache survives untouched.
        let (url_500, _, server_500) =
            serve(vec![http_response("500 Internal Server Error", "", "nope")]);
        assert!(matches!(
            refresh_at(&path, &url_500, 1_000 + STALE_AFTER_SECS).unwrap_err(),
            CatalogError::Http(_)
        ));
        server_500.join().unwrap();

        // 200 with a body that is not a catalog: parse error, cache still untouched.
        let (url_bad, _, server_bad) = serve(vec![http_response("200 OK", "", "{\"acme\": 42}")]);
        assert!(matches!(
            refresh_at(&path, &url_bad, 1_000 + 2 * STALE_AFTER_SECS).unwrap_err(),
            CatalogError::Parse(_)
        ));
        server_bad.join().unwrap();

        let cached: CatalogCache =
            serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
        assert_eq!(
            cached.fetched_at_unix, 1_000,
            "failed refreshes never bump the stamp"
        );
        assert!(cached.catalog.get("acme").is_some());
        assert_eq!(cached.etag.as_deref(), Some("\"e1\""));

        let _ = std::fs::remove_dir_all(&dir);
    }
}
